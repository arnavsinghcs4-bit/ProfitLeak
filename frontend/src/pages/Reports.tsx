import React, { useEffect, useState, useCallback } from "react";
import { useNavigate } from "react-router-dom";
import { useSession } from "@/context/SessionContext";
import { getReports, downloadReportUrl, runAnalysis } from "@/lib/api";
import type { ReportItem } from "@/types/api";
import { fmtBytes } from "@/lib/format";
import {
  PageHeader,
  SectionHeader,
  EmptyState,
  ErrorState,
  LoadingSkeleton,
  Badge,
} from "@/components/ui";
import { useToast } from "@/components/ui/Toast";
import {
  Download,
  FileText,
  FileSpreadsheet,
  Image,
  RefreshCw,
  CheckCircle2,
  AlertCircle,
  Loader2,
} from "lucide-react";

function SectionCard({ children, className = "" }: { children: React.ReactNode; className?: string }) {
  return (
    <div className={`bg-surface border border-border rounded-lg p-5 ${className}`}>
      {children}
    </div>
  );
}

function getReportIcon(key: string) {
  switch (key) {
    case "dashboard_png":
      return <Image size={22} className="text-accent" />;
    case "pivot_workbook":
    case "cleaned_orders":
    case "loss_orders":
      return <FileSpreadsheet size={22} className="text-gain" />;
    case "summary_report":
    default:
      return <FileText size={22} className="text-ink-muted" />;
  }
}

export default function Reports() {
  const { sessionId, meta, refreshSummary } = useSession();
  const navigate = useNavigate();
  const showToast = useToast();

  const [reports, setReports] = useState<ReportItem[]>([]);
  const [loading, setLoading] = useState(false);
  const [regenerating, setRegenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const analyzed = meta?.status === "analyzed";

  const fetchReports = useCallback(async () => {
    if (!sessionId || !analyzed) return;
    setLoading(true);
    setError(null);
    try {
      const res = await getReports(sessionId);
      setReports(res.reports);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to load reports list");
    } finally {
      setLoading(false);
    }
  }, [sessionId, analyzed]);

  useEffect(() => {
    fetchReports();
  }, [fetchReports]);

  const handleRegenerate = async () => {
    if (!sessionId) return;
    setRegenerating(true);
    try {
      await runAnalysis(sessionId, true);
      await refreshSummary();
      await fetchReports();
      showToast("Reports successfully generated", "success");
    } catch (e) {
      showToast(e instanceof Error ? e.message : "Failed to generate reports", "error");
    } finally {
      setRegenerating(false);
    }
  };

  if (!sessionId || !meta) {
    return (
      <div className="px-6 lg:px-8 py-8">
        <PageHeader title="Artifacts & Reports" />
        <EmptyState
          title="No dataset loaded"
          description="Load or upload a dataset to generate and download report artifacts."
          action={
            <button
              onClick={() => navigate("/data")}
              className="text-xs text-accent hover:underline"
            >
              Go to Data Sources
            </button>
          }
        />
      </div>
    );
  }

  if (!analyzed) {
    return (
      <div className="px-6 lg:px-8 py-8">
        <PageHeader title="Artifacts & Reports" />
        <EmptyState
          title="Analysis not run yet"
          description="Execute the analytics pipeline to generate exportable files."
          action={
            <button
              onClick={() => navigate("/data")}
              className="px-3 py-1.5 text-xs font-semibold bg-accent text-canvas rounded-md hover:bg-accent-dim"
            >
              Go to Data Sources
            </button>
          }
        />
      </div>
    );
  }

  return (
    <div className="px-6 lg:px-8 py-8 space-y-6 max-w-5xl mx-auto">
      <PageHeader
        title="Artifacts & Exports"
        description="Download financial forensics artifacts generated by the analytics engine: cleaned datasets, loss registers, Excel pivot workbooks, executive Markdown briefs, and dashboard plots."
        actions={
          <button
            onClick={handleRegenerate}
            disabled={regenerating}
            className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium border border-border text-ink-muted rounded-md hover:text-ink hover:border-ink-faint transition-colors disabled:opacity-50"
          >
            {regenerating ? (
              <Loader2 size={13} className="animate-spin" />
            ) : (
              <RefreshCw size={13} />
            )}
            Regenerate all artifacts
          </button>
        }
      />

      {error && <ErrorState message={error} retry={fetchReports} />}
      {loading && <LoadingSkeleton rows={5} cols={4} />}

      {!loading && reports.length > 0 && (
        <div className="space-y-3">
          {reports.map((report) => {
            const downloadUrl = sessionId ? downloadReportUrl(sessionId, report.key) : "#";
            return (
              <SectionCard
                key={report.key}
                className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 hover:border-border-subtle transition-colors"
              >
                <div className="flex items-start gap-3.5">
                  <div className="p-2.5 rounded-lg bg-elevated shrink-0 mt-0.5">
                    {getReportIcon(report.key)}
                  </div>
                  <div>
                    <div className="flex items-center gap-2">
                      <p className="text-sm font-semibold text-ink font-mono">
                        {report.filename || report.key}
                      </p>
                      {report.exists ? (
                        <Badge tone="gain">Available</Badge>
                      ) : (
                        <Badge tone="warn">Not generated</Badge>
                      )}
                    </div>
                    <p className="text-xs text-ink-muted mt-1 leading-relaxed">
                      {report.description}
                    </p>
                    {report.size_bytes != null && (
                      <p className="text-2xs font-mono text-ink-faint mt-1">
                        Size: {fmtBytes(report.size_bytes)}
                      </p>
                    )}
                  </div>
                </div>

                <div className="shrink-0 flex items-center justify-end">
                  {report.exists ? (
                    <a
                      href={downloadUrl}
                      download={report.filename || undefined}
                      className="flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-semibold bg-elevated border border-border text-ink hover:border-accent hover:text-accent rounded-md transition-colors"
                    >
                      <Download size={13} />
                      Download
                    </a>
                  ) : (
                    <button
                      onClick={handleRegenerate}
                      className="text-xs text-accent hover:underline font-medium"
                    >
                      Generate now
                    </button>
                  )}
                </div>
              </SectionCard>
            );
          })}
        </div>
      )}

      {/* Analytical Documentation Card */}
      <SectionCard className="border-dashed bg-canvas/40">
        <SectionHeader
          title="Data Provenance & Export Governance"
          description="Guidelines on using exported files for accounting and financial reporting."
        />
        <div className="text-xs text-ink-faint space-y-2 leading-relaxed">
          <p>
            • <strong className="text-ink-muted">Cleaned Orders CSV:</strong> Contains all enriched
            vectorized columns including Net Revenue, COGS, Shipping, Net Profit, and Profit Margin.
          </p>
          <p>
            • <strong className="text-ink-muted">Loss Orders CSV:</strong> Filtered to records with
            negative net profit, tagged by heuristic loss causes (Both, Discount-driven,
            Shipping-driven, Cost-driven).
          </p>
          <p>
            • <strong className="text-ink-muted">Analysis Pivots XLSX:</strong> Pre-built multidimensional
            crosstabs (Category × Region, Sub-Category × Month, Segment × Discount Band) ready for
            Excel or PowerBI ingestion.
          </p>
        </div>
      </SectionCard>
    </div>
  );
}
