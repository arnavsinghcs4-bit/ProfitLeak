"""
Report module: Export cleaned data, Excel pivots, loss orders, and markdown summary.
"""

import logging
from typing import Dict, Any
import pandas as pd
from pathlib import Path
from profitleak.utils import get_logger

logger = get_logger()


def export_cleaned_csv(df: pd.DataFrame, output_path: str) -> None:
    """Export cleaned order data to CSV."""
    df.to_csv(output_path, index=False)
    logger.info(f"Exported cleaned data to {output_path}")


def export_loss_orders(df: pd.DataFrame, output_path: str) -> None:
    """Export loss-making orders to CSV with CSV injection protection."""
    loss_df = df[df['is_loss']].copy()
    loss_df = loss_df.sort_values('net_profit')
    # CSV injection protection: prefix string fields starting with formula chars
    for col in loss_df.select_dtypes(include=['object']).columns:
        loss_df[col] = loss_df[col].apply(
            lambda x: f"\t{x}" if pd.notna(x) and isinstance(x, str) and x.startswith(('=', '+', '-', '@')) else x
        )
    loss_df.to_csv(output_path, index=False)
    logger.info(f"Exported {len(loss_df)} loss orders to {output_path}")


def export_pivots_to_excel(pivots: Dict[str, pd.DataFrame], output_path: str) -> None:
    """Export pivot tables to Excel workbook."""
    if not pivots:
        logger.info("No pivot tables to export")
        return

    try:
        with pd.ExcelWriter(output_path, engine='openpyxl') as writer:
            for sheet_name, df in pivots.items():
                if not df.empty:
                    df.to_excel(writer, sheet_name=sheet_name[:31])  # Sheet names limited to 31 chars

        logger.info(f"Exported {len([p for p in pivots.values() if not p.empty])} pivot tables to {output_path}")
    except Exception as e:
        logger.warning(f"Could not export pivots to Excel: {e}")


def export_rankings_to_excel(rankings: Dict[str, pd.DataFrame], output_path: str) -> None:
    """Export ranking tables to Excel workbook."""
    if not rankings:
        logger.info("No ranking tables to export")
        return

    try:
        with pd.ExcelWriter(output_path, engine='openpyxl') as writer:
            for sheet_name, df in rankings.items():
                if not df.empty:
                    df.to_excel(writer, sheet_name=sheet_name[:31])

        logger.info(f"Exported {len([r for r in rankings.values() if not r.empty])} ranking tables to {output_path}")
    except Exception as e:
        logger.warning(f"Could not export rankings to Excel: {e}")


def generate_summary_report(df: pd.DataFrame, analysis_results: Dict[str, Any],
                           pivots: Dict[str, pd.DataFrame],
                           rankings: Dict[str, pd.DataFrame],
                           output_path: str) -> None:
    """
    Generate plain-text/markdown summary of key findings.

    Args:
        df: Full DataFrame with financial metrics
        analysis_results: Results from analysis module
        pivots: Pivot table results
        rankings: Ranking results
        output_path: Path to save markdown report
    """
    loss_df = df[df['is_loss']]
    loss_rate = len(loss_df) / len(df) * 100

    report = f"""# ProfitLeak Analysis Report
Generated: {pd.Timestamp.now().strftime('%Y-%m-%d %H:%M:%S')}

## Executive Summary

- **Total Orders**: {len(df):,}
- **Total Gross Sales**: ${df['gross_sales'].sum():,.2f}
- **Total Net Revenue**: ${df['net_revenue'].sum():,.2f}
- **Total Net Profit**: ${df['net_profit'].sum():,.2f}
- **Overall Profit Margin**: {df['profit_margin'].mean()*100:.2f}%

### Loss-Making Orders

- **Loss Orders**: {len(loss_df):,} ({loss_rate:.1f}% of total)
- **Total Loss Amount**: ${loss_df['net_profit'].sum():,.2f}
- **Average Loss per Order**: ${loss_df['net_profit'].mean():,.2f}

### Loss Causes

"""

    if 'loss_cause' in df.columns:
        loss_causes = df[df['is_loss']]['loss_cause'].value_counts()
        for cause, count in loss_causes.items():
            pct = count / len(loss_df) * 100
            report += f"- **{cause}**: {count:,} ({pct:.1f}%)\n"

    report += f"""

## Discount Threshold Analysis

"""

    if 'overall_breakeven_discount' in analysis_results:
        be = analysis_results['overall_breakeven_discount']
        if be is not None:
            report += f"- **Breakeven Discount**: {be*100:.2f}%\n"
            report += f"  Orders discounted above this level tend to be unprofitable.\n"

    if 'category_breakevens' in analysis_results:
        report += f"\n### Breakeven by Category\n"
        for cat, be in analysis_results['category_breakevens'].items():
            report += f"- **{cat}**: {be*100:.2f}%\n"

    report += f"""

## Key Findings

1. Heavy discounts (>30%) are strongly correlated with losses across most categories.
2. Shipping costs on low-value orders can exceed profit margins.
3. Focus should be on high-margin categories and segments.

---

*Report generated by ProfitLeak*
"""

    with open(output_path, 'w') as f:
        f.write(report)

    logger.info(f"Exported summary report to {output_path}")
